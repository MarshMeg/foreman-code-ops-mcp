package project

import (
	"bytes"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// skipDirs are never searched for service markers.
var skipDirs = map[string]bool{
	"node_modules": true, "vendor": true, "venv": true, "__pycache__": true,
	"dist": true, "build": true, "target": true, "testdata": true, "bin": true, "obj": true,
}

// Discover finds service roots under root by their marker files:
// go.mod (go), pyproject.toml / setup.py (python), tsconfig.json (typescript),
// package.json without tsconfig.json (javascript), Cargo.toml (rust), *.csproj (csharp).
func Discover(root string) ([]Service, error) {
	var found []Service
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		name := d.Name()
		if p != root && (strings.HasPrefix(name, ".") || skipDirs[name]) {
			return filepath.SkipDir
		}
		rel, _ := filepath.Rel(root, p)
		rel = filepath.ToSlash(rel)
		has := func(f string) bool {
			_, err := os.Stat(filepath.Join(p, f))
			return err == nil
		}
		add := func(lang string) {
			found = append(found, Service{Root: rel, Lang: lang})
		}
		if has("go.mod") {
			add("go")
		}
		if has("pyproject.toml") || has("setup.py") {
			add("python")
		}
		if has("Cargo.toml") {
			add("rust")
		}
		if csproj, _ := filepath.Glob(filepath.Join(p, "*.csproj")); len(csproj) > 0 {
			add("csharp")
		}
		switch {
		case has("tsconfig.json"):
			add("typescript")
		case has("package.json"):
			add("javascript")
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	nameServices(found, filepath.Base(root))
	return found, nil
}

// nameServices names each service after its root directory, disambiguating collisions.
func nameServices(svcs []Service, rootName string) {
	count := map[string]int{}
	base := func(s Service) string {
		if s.Root == "." {
			return rootName
		}
		return path.Base(s.Root)
	}
	for _, s := range svcs {
		count[base(s)]++
	}
	used := map[string]bool{}
	for i := range svcs {
		n := base(svcs[i])
		if count[n] > 1 {
			n += "-" + svcs[i].Lang
		}
		for k := 2; used[n]; k++ {
			n = fmt.Sprintf("%s-%s-%d", base(svcs[i]), svcs[i].Lang, k)
		}
		used[n] = true
		svcs[i].Name = n
	}
	sort.SliceStable(svcs, func(i, j int) bool { return svcs[i].Root < svcs[j].Root })
}

// MarshalWorkspace renders a workspace.yaml document with a short header.
func MarshalWorkspace(w Workspace) ([]byte, error) {
	var body bytes.Buffer
	enc := yaml.NewEncoder(&body)
	enc.SetIndent(2)
	if err := enc.Encode(w); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	header := "# Services of this project. Each file belongs to the service with the most specific root;\n" +
		"# the gate, formatters and tests run in that root. Generated by `foreman-code-ops init`.\n"
	return append([]byte(header), body.Bytes()...), nil
}
